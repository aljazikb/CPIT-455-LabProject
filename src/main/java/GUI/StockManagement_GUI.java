    // This method loads all item names from the database
    // and displays them inside the dropdown
    private void loadItemList() {
        ArrayList<String> items = StockManagement.getItemNames();
         // Clear existing items in the dropdown
        MaterialNameCombo.removeAllItems();
        // Add each item name into the dropdown
        for (String item : items) {
            MaterialNameCombo.addItem(item);
        }
    }

