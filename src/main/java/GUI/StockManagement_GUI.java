    private void CheckStatusButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CheckStatusButtonActionPerformed
     
      
    // Get selected material name from dropdown
    String itemName = (String) MaterialNameCombo.getSelectedItem();
     // Get minimum limit value from text field and remove spaces
    String minLimit = limitText.getText().trim();

    // Check if input is empty
    if (minLimit.isEmpty()) {
        showErrorPopup("Please fill in all fields");
        return;
    }

    try {
         // Convert input from String to Integer
        int minLimitInt = Integer.parseInt(minLimit);

        //ONLY CALL LOGIC CLASS
        String result = StockManagement.checkStatus(itemName, minLimitInt);

        // Display result in UI label only
        alertLabel.setText( result);

        // optional popup
        //showSuccessPopup(result);

    } catch (NumberFormatException e) {
        // If user entered letters instead of numbers
        showErrorPopup("Min Limit must be a number");
    }
  
    }//GEN-LAST:event_CheckStatusButtonActionPerformed

    private void AddNewMaterialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddNewMaterialActionPerformed
        // TODO add your handling code here:
        
        javax.swing.JTextField nameEntery = new javax.swing.JTextField(22);
        javax.swing.JTextField quantityEntery = new javax.swing.JTextField(22);

        Color fieldBg = new Color(20, 40, 70);
        Font fieldFont = new Font("Tw Cen MT Condensed", Font.PLAIN, 20);

        for (javax.swing.JTextField f : new javax.swing.JTextField[]{nameEntery, quantityEntery}) {
            f.setBackground(fieldBg);
            f.setForeground(Color.WHITE);
            f.setCaretColor(Color.WHITE);
            f.setFont(fieldFont);
            f.setBorder(javax.swing.BorderFactory.createCompoundBorder(
                    javax.swing.BorderFactory.createLineBorder(new Color(41, 128, 185), 1),
                    javax.swing.BorderFactory.createEmptyBorder(4, 8, 4, 8)
            ));
        }

        // ── Labels ──
        Font labelFont = new Font("Tw Cen MT Condensed", Font.BOLD, 20);
        javax.swing.JLabel lName = new javax.swing.JLabel("Material Name:");
        javax.swing.JLabel lQty = new javax.swing.JLabel("Quantity:");

        for (javax.swing.JLabel l : new javax.swing.JLabel[]{lName, lQty}) {
            l.setFont(labelFont);
            l.setForeground(Color.WHITE);
        }

        // ── Panel ──
        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(3, 2, 10, 14));
        panel.setBackground(new Color(30, 58, 95));
        panel.setBorder(javax.swing.BorderFactory.createEmptyBorder(20, 24, 20, 24));
        panel.add(lName);
        panel.add(nameEntery);
        panel.add(lQty);
        panel.add(quantityEntery);

        // ── Style the JOptionPane to match app theme ──
        javax.swing.UIManager.put("OptionPane.background", new Color(30, 58, 95));
        javax.swing.UIManager.put("Panel.background", new Color(30, 58, 95));
        javax.swing.UIManager.put("OptionPane.messageForeground", Color.WHITE);
        javax.swing.UIManager.put("Button.background", new Color(52, 73, 94));
        javax.swing.UIManager.put("Button.foreground", Color.WHITE);
        javax.swing.UIManager.put("Button.font", new Font("Tw Cen MT Condensed", Font.PLAIN, 18));

        int result = javax.swing.JOptionPane.showConfirmDialog(
                this, panel,
                "Add New Material",
                javax.swing.JOptionPane.OK_CANCEL_OPTION,
                javax.swing.JOptionPane.PLAIN_MESSAGE
        );

        // ── Reset UIManager so other dialogs are not affected ──
        javax.swing.UIManager.put("OptionPane.background", null);
        javax.swing.UIManager.put("Panel.background", null);
        javax.swing.UIManager.put("OptionPane.messageForeground", null);
        javax.swing.UIManager.put("Button.background", null);
        javax.swing.UIManager.put("Button.foreground", null);
        javax.swing.UIManager.put("Button.font", null);

        
        
        //The call for method Start from here
        //If user cancels, stop execution
        if (result != javax.swing.JOptionPane.OK_OPTION) {
            return;
        }

        // Get user input
        String name = nameEntery.getText().trim();
        String quantityStr = quantityEntery.getText().trim();


        // Validate empty fields
        if (name.isEmpty() || quantityStr.isEmpty()) {
            showErrorPopup("Please fill all fields");
            return;
        }

        try {
            // Convert quantity to number
            int quantity = Integer.parseInt(quantityStr);

            // Validate quantity
            if (quantity < 0) {
                showErrorPopup("Quantity cannot be negative");
                return;
            }

            //  DB CALL
            StockManagement.addNewMaterial(name, quantity);

            // Update UI (combo box)
            MaterialNameCombo.addItem(name);
            MaterialNameCombo.setSelectedItem(name);

            // SUCCESS
            showSuccessPopup("Material \"" + name + "\" added successfully");

        } catch (NumberFormatException e) {
            showErrorPopup("Quantity must be a valid number");
        }

    }//GEN-LAST:event_AddNewMaterialActionPerformed

    
    
