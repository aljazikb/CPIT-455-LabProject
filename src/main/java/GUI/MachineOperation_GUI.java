    private int showConfirmPopup(String message) {

        // Panel
        javax.swing.JPanel panel = new javax.swing.JPanel();
        panel.setBackground(new java.awt.Color(30, 58, 95));
        panel.setLayout(new java.awt.BorderLayout(10, 10));

        // Label
        javax.swing.JLabel label = new javax.swing.JLabel("<html>" + message.replace("\n", "<br>") + "</html>");
        label.setForeground(java.awt.Color.WHITE);
        label.setFont(new java.awt.Font("Tw Cen MT Condensed", java.awt.Font.BOLD, 20));
        label.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);

        panel.add(label, java.awt.BorderLayout.CENTER);

        // Buttons
        String[] options = {"Yes", "No"};

        return javax.swing.JOptionPane.showOptionDialog(
                this,
                panel,
                "Confirmation",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.PLAIN_MESSAGE,
                null,
                options,
                options[0]
        );
    }
    
    
