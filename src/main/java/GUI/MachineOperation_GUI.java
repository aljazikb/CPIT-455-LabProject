    private void PerformanceResultActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_PerformanceResultActionPerformed
         // Get selected machine name from dropdown
        String machineName = (String) NameMachine.getSelectedItem();

         // Call backend logic to calculate machine performance
        MachineOperation.MachineResult r = MachineOperation.performanceCalc(machineName);

       // Display result message in UI text area 
        ResultText.setText(r.output);

        // If machine needs maintenance, ask user for confirmation
        if (r.needsMaintenance) {
            int choice = showConfirmPopup("Machine performance is LOW.\n Need to perform Maintenance?");

            // If user clicks YES
            if (choice == JOptionPane.YES_OPTION) {
                // Update machine status in database to "Maintenance"
                MachineOperation.updateMachineStatus(machineName, "Maintenance");
                 // Show success message
                showSuccessPopup("Updated successfully");
            }
        }


    }//GEN-LAST:event_PerformanceResultActionPerformed

