    private void AddNewMachineBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddNewMachineBtnActionPerformed
        
    JTextField nameField = new JTextField(22);
    JTextField usageField = new JTextField("0", 22);
    JTextField statusField = new JTextField("Idle", 22);

    statusField.setEditable(false);
    usageField.setEditable(false);

    Color fieldBg = new Color(20, 40, 70);
    Font fieldFont = new Font("Tw Cen MT Condensed", Font.PLAIN, 20);

    for (JTextField f : new JTextField[]{nameField, usageField, statusField}) {
        f.setBackground(fieldBg);
        f.setForeground(Color.WHITE);
        f.setCaretColor(Color.WHITE);
        f.setFont(fieldFont);
        f.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(new Color(41, 128, 185), 1),
                BorderFactory.createEmptyBorder(4, 8, 4, 8)
        ));
    }

    Font labelFont = new Font("Tw Cen MT Condensed", Font.BOLD, 20);

    JLabel lName = new JLabel("Machine Name:");
    JLabel lUsage = new JLabel("Default Usage Time:");
    JLabel lDefaultStatus = new JLabel("Default Status:");

    for (JLabel l : new JLabel[]{lName, lUsage, lDefaultStatus}) {
        l.setFont(labelFont);
        l.setForeground(Color.WHITE);
    }

    JPanel panel = new JPanel(new GridLayout(3, 2, 10, 14));
    panel.setBackground(new Color(30, 58, 95));
    panel.setBorder(BorderFactory.createEmptyBorder(20, 24, 20, 24));

    panel.add(lName);
    panel.add(nameField);
    panel.add(lUsage);
    panel.add(usageField);
    panel.add(lDefaultStatus);
    panel.add(statusField);

    UIManager.put("OptionPane.background", new Color(30, 58, 95));
    UIManager.put("Panel.background", new Color(30, 58, 95));
    UIManager.put("OptionPane.messageForeground", Color.WHITE);
    UIManager.put("Button.background", new Color(52, 73, 94));
    UIManager.put("Button.foreground", Color.WHITE);

    int result = JOptionPane.showConfirmDialog(this,panel,"Add New Machine",JOptionPane.OK_CANCEL_OPTION,JOptionPane.PLAIN_MESSAGE );

    UIManager.put("OptionPane.background", null);
    UIManager.put("Panel.background", null);
    UIManager.put("OptionPane.messageForeground", null);
    UIManager.put("Button.background", null);
    UIManager.put("Button.foreground", null);

    
    //The call for method Start from here
    
    if (result != JOptionPane.OK_OPTION) {
        return;
    }

    String name = nameField.getText().trim();

    if (name.isEmpty()) {
        showErrorPopup("The Name field is required.");
        return;
    }

    try {
        int newID = MachineOperation.addMachine(name);

        if (newID == -1) {
            showErrorPopup("Machine already exists.");
        } else {
            showSuccessPopup("\"" + name + "\" added successfully!\n"+ "   Machine ID: " + newID + "\n"+ "  Default Status: Idle");
        }

    } catch (SQLException e) {
        showErrorPopup("Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_AddNewMachineBtnActionPerformed

